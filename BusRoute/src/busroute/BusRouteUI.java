    private Route createRoute() {

        String type = (String) jComboBox1.getSelectedItem();

        String start = startTextField.getText().trim();

        String end = endTextField.getText().trim();

        String distanceText = distanceTextField.getText().trim();

        // Validate empty fields
        if (start.isEmpty() || end.isEmpty()
                || distanceText.isEmpty()) {

            throw new IllegalArgumentException(
                "Please fill in all fields!"
            );
        }

        double distance;

        // Validate distance
        try {

            distance = Double.parseDouble(distanceText);

        } catch (NumberFormatException e) {

            throw new IllegalArgumentException(
                "Please enter a valid distance!"
            );
        }

        if (!Double.isFinite(distance) || distance <= 0) {

            throw new IllegalArgumentException(
                "Distance must be greater than zero!"
            );
        }

        // Validate locations
        if (start.equalsIgnoreCase(end)) {

            throw new IllegalArgumentException(
                "Start and End cannot be the same!"
            );
        }

        // Create the appropriate child object
        switch (type) {

            case "BarisalRoute":
                return new BarisalRoute(start, end, distance);

            case "JhalokathiRoute":
                return new JhalokathiRoute(start, end, distance);

            case "PatukhaliRoute":
                return new PatukhaliRoute(start, end, distance);

            default:
                throw new IllegalArgumentException(
                    "Please select a valid route type!"
                );
        }
    }


